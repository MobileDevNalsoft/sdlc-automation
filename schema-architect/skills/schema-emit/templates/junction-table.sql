-- ----------------------------------------------------------------------------
-- 3. FK INDEXES -- mandatory (schema-model.md §8: Oracle never auto-indexes
--    an FK column). product_id is already the leading column of
--    app_product_category_uk1, so it does not need a second index.
--    category_id is NOT the leading column of any existing index here, so
--    its FK index is required, not optional.
-- ----------------------------------------------------------------------------
DECLARE
   l_count PLS_INTEGER;
BEGIN
   SELECT COUNT(*) INTO l_count FROM user_indexes WHERE index_name = 'APP_PRODUCT_CATEGORY_IDX1';

   IF l_count = 0 THEN
      EXECUTE IMMEDIATE '
         CREATE INDEX app_product_category_idx1 ON app_product_category_t (category_id)';
   END IF;
END;
